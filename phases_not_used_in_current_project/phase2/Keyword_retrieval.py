from pathlib import Path
import pickle
import re


BM25_INDEX_PATH = (
    Path(__file__).resolve().parent / "bm25_index.pkl"
)


def tokenize(text):
    return re.findall(r"\b\w+\b", text.lower())


class KeywordRetriever:

    def __init__(self, top_k=5):

        self.top_k = top_k

        print("Loading saved BM25 index...")

        if not BM25_INDEX_PATH.exists():
            raise FileNotFoundError(
                "BM25 index not found. "
                "Run phase1/ingest.py first."
            )

        # Only load pickle files generated by your own ingestion.
        with open(BM25_INDEX_PATH, "rb") as file:
            index_data = pickle.load(file)

        self.bm25 = index_data["bm25"]
        self.chunks = index_data["chunks"]

        print(f"Loaded {len(self.chunks)} indexed chunks.")
        print("Keyword retriever initialized successfully.")

    def retrieve(self, query):

        if not query or not query.strip():
            raise ValueError("Query cannot be empty.")

        scores = self.bm25.get_scores(tokenize(query))

        ranked_indices = sorted(
            range(len(scores)),
            key=lambda index: scores[index],
            reverse=True
        )

        results = []

        for index in ranked_indices[:self.top_k]:

            chunk = self.chunks[index]

            results.append({
                "id": chunk["id"],
                "text": chunk["text"],
                "page": chunk["page"],
                "score": float(scores[index])
            })

        return results


if __name__ == "__main__":

    retriever = KeywordRetriever(top_k=5)

    query = "Why did Kattappa kill Baahubali?"
    results = retriever.retrieve(query)

    print(f"\nQuery: {query}")
    print("=" * 60)

    for rank, result in enumerate(results, start=1):

        print(f"\nRank: {rank}")
        print(f"Chunk ID: {result['id']}")
        print(f"Page: {result['page']}")
        print(f"BM25 Score: {result['score']:.4f}")
        print(f"Text: {result['text'][:300]}...")
